# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

def database_config_from_url(url):
    """Build the Django ``DATABASES['default']`` entry from a database URL.

    MySQL 8+ is the only supported engine and the scheme check below is load
    bearing, not defensive boilerplate: the order/inventory code depends on real
    ``SELECT ... FOR UPDATE`` row locking, which several other backends accept
    and silently ignore.

    Shared by ``dev`` and ``test`` so both parse a URL the same way — ``test``
    calls it again when ``TEST_DATABASE_URL`` is set.
    """
    normalized_url = re.sub(r'^mysql\+[a-zA-Z0-9_]+://', 'mysql://', url)
    db_parsed = urlparse(normalized_url)

    if db_parsed.scheme != 'mysql':
        raise RuntimeError(f"Unsupported database scheme: '{db_parsed.scheme}'. MySQL 8+ is required.")

    return {
        'ENGINE': 'django.db.backends.mysql',
        'NAME': db_parsed.path.lstrip('/'),
        'USER': db_parsed.username or '',
        'PASSWORD': unquote(db_parsed.password) if db_parsed.password else '',
        'HOST': db_parsed.hostname or '127.0.0.1',
        'PORT': db_parsed.port or 3306,
        'OPTIONS': {
            'charset': 'utf8mb4',
            'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
        },
        'TEST': {
            'CHARSET': 'utf8mb4',
            'COLLATION': 'utf8mb4_unicode_ci',
        },
    }


